import os, shutil
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

pd.set_option("display.width", 220)
D = "data/selected"
os.makedirs("results", exist_ok=True)

low = pd.read_csv(f"{D}/lowN_results.csv")
act = pd.read_csv(f"{D}/active_results.csv")
base = pd.read_csv(f"{D}/baselines.csv")

MODELS = ["zero_shot", "additive_onehot", "ridge_mean", "ridge_pos", "ridge_pos+zs"]
STRATS = ["random", "zs_greedy", "greedy", "ucb", "uncertainty"]

# ---- Table 1: low-N Spearman, averaged over assays (each assay averaged over seeds first)
pa = low.groupby(["split", "n", "model", "DMS_id"])["rho"].mean().reset_index()
t1 = pa.groupby(["split", "n", "model"])["rho"].mean().unstack("model")[MODELS]

# ---- Table 2: per-assay, position-held-out, gain over zero-shot
parts = {}
for n in [24, 192]:
    p = pa[(pa.split == "position_heldout") & (pa.n == n)].pivot_table(
        index="DMS_id", columns="model", values="rho")[["zero_shot", "ridge_pos+zs"]]
    p["gain"] = p["ridge_pos+zs"] - p["zero_shot"]
    parts[f"N={n}"] = p
t2 = pd.concat(parts, axis=1)
t2.columns = [f"{a} | {b}" for a, b in t2.columns]

# ---- Table 3: active learning enrichment
pact = act.groupby(["group", "DMS_id", "strategy", "n_labels"])["enrichment"].mean().reset_index()
t3 = pact.groupby(["n_labels", "strategy"])["enrichment"].mean().unstack("strategy")[STRATS]
t3 = t3.loc[[24, 48, 72, 96, 144, 192]]
t3g = pact.groupby(["group", "n_labels", "strategy"])["enrichment"].mean().unstack("strategy")[STRATS]
t3g = t3g[t3g.index.get_level_values("n_labels").isin([48, 96, 192])]

# ---- Table 4: paired difference vs random at 192 labels, mean +/- SE over 20 seeds
f = act[act.n_labels == 192].pivot_table(index=["DMS_id", "seed"], columns="strategy",
                                         values="enrichment")
out = {}
for s in STRATS[1:]:
    d = (f[s] - f["random"]).groupby("DMS_id").agg(["mean", "std", "count"])
    out[s] = d.apply(lambda r: f"{r['mean']:+.2f} ± {r['std'] / np.sqrt(r['count']):.2f}", axis=1)
t4 = pd.DataFrame(out)

# ---- Write markdown + CSVs
with open("results/RESULTS.md", "w") as fh:
    def sec(title, df, note="", fmt=".3f"):
        fh.write(f"## {title}\n\n{note}\n\n{df.to_markdown(floatfmt=fmt)}\n\n")
    fh.write("# Results (auto-generated by make_report.py)\n\n")
    sec("Low-N Spearman, averaged over 8 assays", t1,
        "Mean over assays of per-assay means (20 seeds each).")
    sec("Per-assay Spearman, position-held-out split", t2,
        "Gain = ridge_pos+zs minus zero_shot.")
    sec("Active learning: top-5% enrichment (1.0 = random)", t3,
        "Average over assays. All strategies share the same random first 24 labels.", ".2f")
    sec("Active learning by prior-strength group (exploratory, defined post hoc)", t3g, "", ".2f")
    sec("Enrichment difference vs random at 192 labels, per assay (mean ± SE over 20 seeds)", t4)
    sec("Step 4 baselines (single mutants, 80/20 random split)", base.set_index("DMS_id"))

t1.to_csv("results/lowN_summary.csv"); t2.to_csv("results/lowN_per_assay.csv")
t3.to_csv("results/active_summary.csv"); t4.to_csv("results/active_vs_random.csv")
for fn in ["lowN_results.csv", "active_results.csv", "baselines.csv",
           "lowN_random.png", "lowN_position_heldout.png", "active_per_assay.png"]:
    if os.path.exists(f"{D}/{fn}"):
        shutil.copy(f"{D}/{fn}", f"results/{fn}")

# ---- Summary figure for the README
fig, axes = plt.subplots(1, 3, figsize=(16, 4.5), sharey=True)
panels = [("all 8 assays", pact),
          ("prior-strong (3 assays)", pact[pact.group == "prior_strong"]),
          ("prior-weak (5 assays)", pact[pact.group == "prior_weak"])]
for ax, (title, d) in zip(axes, panels):
    c = d.groupby(["strategy", "n_labels"])["enrichment"].mean().unstack("strategy")
    for s in STRATS:
        ax.plot(c.index, c[s], marker="o", label=s)
    ax.axhline(1, ls="--", color="gray")
    ax.set_title(title); ax.set_xlabel("labels used"); ax.grid(alpha=0.3)
axes[0].set_ylabel("top-5% enrichment (1 = random)")
axes[0].legend()
fig.tight_layout()
fig.savefig("results/active_summary.png", dpi=150)

print("Wrote results/RESULTS.md and results/active_summary.png\n")
print("=== Per-assay held-out table ===")
print(t2.round(3).to_string())
print("\n=== Enrichment difference vs random at 192 labels (mean ± SE) ===")
print(t4.to_string())